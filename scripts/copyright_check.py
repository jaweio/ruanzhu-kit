def check_sources(repo, cfg, F):
    holder_tok = _own_tokens(cfg, repo)
    self_oss = bool(cfg.get("self_open_source"))
    owner = defaultdict(list)
    bad_files = set()
    for proj in cfg.get("projects", []):
        for rel in proj.get("source_files", []):
            owner[rel].append(proj.get("name", proj.get("id")))
    for rel, names in owner.items():
        if len(names) > 1:
            F.add("high", "取材", rel, "同一源文件被多份软著取材", "、".join(names),
                  "黄金原则 2：每个文件只能归属一份软著")
            bad_files.add(rel)

    for rel in owner:
        where = rel
        if THIRD_PARTY_PATH.search(rel):
            F.add("high", "取材", where, "第三方/构建产物路径", rel, "从 source_files 中剔除，改选自研目录下的文件")
            bad_files.add(rel)
        if TYPE_DECL.search(rel):
            F.add("low", "取材", where, "类型声明文件（.d.ts）", rel,
                  "只有声明、没有业务逻辑，第三方 SDK 的声明文件更不应取材；建议换成实现文件")
        if GENERATED_PATH.search(rel):
            F.add("medium", "取材", where, "工具生成文件", rel, "生成代码不体现独创性，建议剔除")
            bad_files.add(rel)
        p = repo / rel
        if not p.exists():
            F.add("medium", "取材", where, "文件不存在", str(p), "检查 --repo 路径或更新 source_files")
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        lines = text.splitlines()
        if lines and (max(len(l) for l in lines) > 1000 or sum(len(l) for l in lines) / len(lines) > 250):
            F.add("high", "取材", where, "压缩/打包代码", f"平均行长 {sum(len(l) for l in lines) // len(lines)}",
                  "非手写源码，剔除")
            bad_files.add(rel)
        head = "\n".join(lines[:60])
        head_owners = [re.sub(r"^[-–\s]*(?:present|now)?[,\s]*", "", m.group(1)).strip()
                       for m in COPYRIGHT_LINE.finditer(head)]
        own_head = holder_tok and all(_is_own(w, holder_tok) for w in head_owners if w.strip(" .,")) and \
            (head_owners or self_oss)
        for kind, pat, sev in LICENSE_TEXT:
            if re.search(pat, head, re.I) and own_head:
                F.add("low", "取材", f"{where}:1-60", f"自有许可证头（{kind}）", re.search(pat, head, re.I).group(0),
                      "提取时自动整块删除")
                break
            if re.search(pat, head, re.I):
                vendor = ENGINE_VENDORS.search(head)
                advice = ("文件由引擎/框架模板生成（" + vendor.group(0) + "）后修改：原声明必须保留，"
                          "不宜作为源程序材料，换成其他完全自研的文件" if vendor else
                          "这是第三方或已开源代码：不得删除许可证头冒充自研，应从 source_files 剔除")
                F.add(sev, "取材", f"{where}:1-60", f"文件头含开源许可证（{kind}）", re.search(pat, head, re.I).group(0),
                      advice)
                bad_files.add(rel)
                break
        for m in COPYRIGHT_LINE.finditer(head):
            who = re.sub(r"^[-–\s]*(?:present|now)?[,\s]*", "", m.group(1)).strip()
            if re.search(r"^\s*$|^[\W\d]+$", who):
                continue
            if not holder_tok or not _is_own(who, holder_tok):
                sev = "high" if holder_tok else "medium"
                F.add(sev, "取材", where, "文件含他人（或未核实）版权声明", who,
                      "版权人不是申报主体：剔除该文件；若就是本公司的旧名/英文名，在 config 的 copyright_holder 核对后忽略")
                if holder_tok:
                    bad_files.add(rel)
                break
        from oss_scrub import REF_URL, REF_WORDS
        ref_words = re.compile(REF_WORDS, re.I)
        for no, line in enumerate(lines, 1):
            loc = f"{where}:{no}"
            for m in REPO_URL.finditer(line):
                repo_owner = re.search(r"\.(?:com|org|net)/([\w.-]+)/", m.group(0))
                if repo_owner and _is_own(repo_owner.group(1), holder_tok):
                    F.add("low", "取材", loc, "代码中含自有仓库链接", m.group(0), "提取时自动清除")
                else:
                    F.add("medium", "取材", loc, "代码中含他人仓库链接", m.group(0),
                          "提取时自动清除链接；但要确认这段代码是否取自该仓库，是则换文件")
            for m in REF_URL.finditer(line):
                F.add("medium", "取材", loc, "代码引用博客/问答来源", m.group(0),
                      "提取时自动删除该地址；但该段可能摘自网络，须确认改写程度，或换文件取材")
            if ref_words.search(line):
                F.add("medium", "取材", loc, "注释写明代码来源", line.strip()[:80],
                      "提取时自动删除该注释；但须核实原作者与许可，照搬的代码应换文件")
            if GENERATED_MARK.search(line) and no <= 30:
                F.add("medium", "取材", loc, "自动生成代码标记", line.strip()[:80], "生成代码建议剔除")
                bad_files.add(rel)
            if AI_MARK.search(line):
                F.add("medium", "取材", loc, "AI 生成标记", line.strip()[:80],
                      "如实评估人工修改程度；材料中不宜保留该注释的同时声称全部独立手写")
            for _start, _end, names in secret_hits(line):
                # 先脱敏再做显示截断：mask() 只缩短长标识符，单用会把口令前 4 位写进报告。
                F.add("high", "取材", loc, f"敏感信息：{'／'.join(names)}",
                      mask(redact_line(line.strip())[:80]),
                      "立即轮换该密钥；提取时自动脱敏（generate_source_docx.py 默认开启）")
            for name, pat in PII:
                for m in re.finditer(pat, line):
                    if not PII_ALLOW.search(m.group(0)):
                        F.add("low", "取材", loc, f"个人信息：{name}", mask(m.group(0)), "提取时自动脱敏")
        for m in AUTHOR_TAG.finditer(head):
            who = (m.group(1) or m.group(2) or "").strip()
            if who and holder_tok and not any(t in who for t in holder_tok):
                F.add("low", "取材", where, "@author 与著作权人不同", who,
                      "员工/外包作者需确认职务作品或委托开发协议")
                break
        for sname, pat in SCAFFOLDS:
            if pat.search(head) or pat.search(rel):
                F.add("high", "取材", where, f"取自开源项目：{sname}", pat.pattern, "剔除，改选自研文件")
                bad_files.add(rel)
                break
    # 提取时会被自动跳过的第三方文件：不会进入材料，降为中风险，只提示补选文件
    from oss_scrub import third_party_reasons
    auto_skip = set()
    for rel in owner:
        p = repo / rel
        if p.exists() and third_party_reasons(rel, p.read_text(encoding="utf-8", errors="ignore"), holder_tok):
            auto_skip.add(rel)
    for item in F.items:
        f = item["where"].split(":")[0]
        if item["layer"] == "取材" and f in auto_skip and item["severity"] == "high" and "多份软著" not in item["rule"]:
            item["severity"] = "medium"
            item["advice"] = "提取时自动跳过，不进入材料；请从 source_files 移除并补选自研文件，保证行数"
    return bad_files


