class Findings:
    def __init__(self):
        self.items = []

    def add(self, sev, layer, where, rule, detail, advice):
        self.items.append({"severity": sev, "layer": layer, "where": where, "rule": rule,
                           "detail": detail[:160], "advice": advice})

    def count(self, sev):
        return sum(1 for i in self.items if i["severity"] == sev)


def mask(s):
    return re.sub(r"[A-Za-z0-9_-]{8,}", lambda m: m.group(0)[:4] + "****", s)


def holder_tokens(holder):
    """著作权人名称的可比对片段：全称、去掉“有限公司”等后缀的简称。"""
    if not holder or holder.startswith("【"):
        return []
    core = re.sub(r"(?:股份)?有限(?:责任)?公司|工作室|科技|信息技术|网络|集团|（.*?）|\(.*?\)", "", holder)
    return [t for t in {holder, core} if len(t) >= 2]


