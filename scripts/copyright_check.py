def render(F, cfg, bad_files):
    rows = sorted(F.items, key=lambda i: (SEV_ORDER[i["severity"]], i["layer"], i["where"]))
    holder = configured_fact(cfg.get("copyright_holder", "")) or "未填写"
    out = ["# 版权风险检查报告", "",
           f"> 著作权人：{holder}　｜　"
           f"高 {F.count('high')} ／ 中 {F.count('medium')} ／ 低 {F.count('low')}",
           "> 本报告只做线索排查，不构成法律意见；高风险项处理完再进入 PDF 渲染与填表。", ""]
    if bad_files:
        out += ["## 建议从 source_files 剔除", "", "| 文件 |", "| --- |"] + [f"| `{f}` |" for f in sorted(bad_files)]
        out += ["", "用 `--suggest-config` 生成剔除后的配置建议稿，补足行数后再重新提取源程序。", ""]
    # 同一文件同一规则的逐行命中合并展示
    grouped = defaultdict(list)
    for r in rows:
        key = (r["severity"], r["layer"], r["where"].split(":")[0], r["rule"])
        grouped[key].append(r)
    for sev in ("high", "medium", "low"):
        keys = [k for k in grouped if k[0] == sev]
        if not keys:
            continue
        out += [f"## {SEV_CN[sev]}风险（{sum(len(grouped[k]) for k in keys)}）", "",
                "| 层 | 位置 | 问题 | 线索 | 处理建议 |", "| --- | --- | --- | --- | --- |"]
        for k in keys:
            items = grouped[k]
            locs = [i["where"] for i in items]
            if len(locs) == 1:
                where = locs[0]
            elif ":" in locs[0]:
                where = f"{k[2]}（{len(locs)} 处，行 " + "、".join(l.split(":")[-1] for l in locs[:5]) + "）"
            else:
                where = f"{k[2]}（{len(locs)} 处）"
            detail = "；".join(dict.fromkeys(i["detail"] for i in items))[:160]
            detail = detail.replace("|", "\\|").replace("\n", " ")
            out.append(f"| {k[1]} | `{where}` | {k[3]} | {detail} | {items[0]['advice']} |")
        out.append("")
    if not rows:
        out.append("未发现版权风险线索。")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description="软著材料版权风险检查")
    ap.add_argument("--config", default="soft-copyright-materials/ruanzhu.config.json")
    ap.add_argument("--repo", default=".", help="被申报项目的源码根目录")
    ap.add_argument("--report", help="Markdown 报告输出路径（默认 <output_root>/版权风险检查报告.md）")
    ap.add_argument("--json", help="JSON 结果输出路径")
    ap.add_argument("--skip", nargs="*", default=[], choices=["project", "sources", "materials"])
    ap.add_argument("--fail-on", choices=["high", "medium"], help="存在该级别及以上风险时退出码 1")
    ap.add_argument("--suggest-config", action="store_true",
                    help="写出 ruanzhu.config.suggested.json（剔除高风险文件，不覆盖原配置）")
    args = ap.parse_args()

    cfg_path = Path(args.config)
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    repo = Path(args.repo).resolve()
    root = Path(cfg.get("output_root", "soft-copyright-materials"))
    F = Findings()
    bad = set()
    if "project" not in args.skip:
        check_project(repo, cfg, F)
    if "sources" not in args.skip:
        bad = check_sources(repo, cfg, F)
    if "materials" not in args.skip:
        check_materials(root, cfg, F)

    report = Path(args.report) if args.report else root / "版权风险检查报告.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render(F, cfg, bad), encoding="utf-8")
    if args.json:
        Path(args.json).write_text(json.dumps(F.items, ensure_ascii=False, indent=2), encoding="utf-8")
    if args.suggest_config and bad:
        sug = json.loads(json.dumps(cfg))
        for proj in sug.get("projects", []):
            before = len(proj.get("source_files", []))
            proj["source_files"] = [f for f in proj.get("source_files", []) if f not in bad]
            proj["_removed_by_copyright_check"] = before - len(proj["source_files"])
        out = cfg_path.with_name("ruanzhu.config.suggested.json")
        out.write_text(json.dumps(sug, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"配置建议稿：{out}（确认后手动替换原配置，并补充取材文件保证行数）")
    print(f"高 {F.count('high')} / 中 {F.count('medium')} / 低 {F.count('low')}  报告：{report}")
    if args.fail_on:
        limit = SEV_ORDER[args.fail_on]
        if any(SEV_ORDER[i["severity"]] <= limit for i in F.items):
            sys.exit(1)


if __name__ == "__main__":
    main()
