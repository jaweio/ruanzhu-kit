def git(repo, *args):
    try:
        return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=20).stdout
    except (OSError, subprocess.TimeoutExpired):
        return ""


def _own_tokens(cfg, repo=None):
    from oss_scrub import own_tokens
    return own_tokens(cfg, repo)


def _is_own(who, tokens):
    return any(t.lower() in who.lower() for t in tokens)


OWN_OSS_ADVICE = "自有开源：材料生成时自动清除（源程序 generate_source_docx.py，说明书 oss_scrub.py）；源程序须取自申报的上架版本"


def check_project(repo, cfg, F):
    tokens = _own_tokens(cfg, repo)
    self_oss = bool(cfg.get("self_open_source"))
    for name in LICENSE_FILES:
        p = repo / name
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")[:6000]
        kind = next((k for k, pat, _ in LICENSE_TEXT if re.search(pat, text, re.I)), "未识别")
        owners = [re.sub(r"^[-–\s]*(?:present|now)?[,\s]*", "", m.group(1)).strip() for m in COPYRIGHT_LINE.finditer(text)]
        own_license = self_oss and all(_is_own(w, tokens) for w in owners if w)
        if own_license:
            F.add("low", "项目", name, f"自有开源项目（{kind}）", "、".join(owners)[:60], OWN_OSS_ADVICE)
            continue
        sev = "high" if "GPL" in kind else "medium"
        F.add(sev, "项目", name, f"项目含开源许可证（{kind}）",
              text.strip().splitlines()[0] if text.strip() else "",
              "若是自己开源的项目：在 config 设 self_open_source=true 并把 GitHub/Gitee 账号、英文名写进 self_aliases；"
              "否则确认权利归属后再申报")
        for who in owners:
            if tokens and who and not _is_own(who, tokens) and not re.search(r"<?year>?|\[yyyy\]|\{\{", who, re.I):
                F.add("high", "项目", name, "LICENSE 中的版权人与申报著作权人不一致", who,
                      "说明项目可能是他人项目的 fork/二次开发；须确认原作者授权，或只申报自己新增的独立部分")
                break

    for manifest in ("package.json", "composer.json", "pyproject.toml", "setup.py", "Cargo.toml", "pom.xml",
                     "build.gradle", "pubspec.yaml", "go.mod"):
        p = repo / manifest
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8", errors="ignore")
        head = text[:20000]
        lic = re.search(r"[\"']?license[\"']?\s*[:=]\s*[\"']([^\"']+)|<license>\s*<name>([^<]+)", head, re.I)
        if lic and self_oss:
            F.add("low", "项目", manifest, "包清单声明了开源许可证（自有）", (lic.group(1) or lic.group(2)).strip(),
                  OWN_OSS_ADVICE)
        elif lic:
            F.add("medium", "项目", manifest, "包清单声明了开源许可证", (lic.group(1) or lic.group(2)).strip(),
                  "自有开源项目：设 self_open_source=true 并补 self_aliases；否则确认代码来源")
        for m in re.finditer(r"[\"']?(?:author|authors|contributors)[\"']?\s*[:=]\s*[\[\"']?([^\"'\]\n]{2,80})", head, re.I):
            who = m.group(1).strip()
            if tokens and not _is_own(who, tokens):
                F.add("low", "项目", manifest, "包清单作者与著作权人不同", mask(who),
                      "员工职务作品可以；外部作者需确认权利归属")
                break
        for m in REPO_URL.finditer(head):
            F.add("low" if self_oss else "medium", "项目", manifest, "包清单含代码仓库地址", m.group(0),
                  OWN_OSS_ADVICE if self_oss else "仓库地址不得出现在申报材料中；如为自有仓库，补 self_aliases")
            break
        for sname, pat in SCAFFOLDS:
            if pat.search(head) and not _is_own(sname, tokens):
                F.add("high", "项目", manifest, f"疑似基于开源项目：{sname}", pat.pattern,
                      "只能申报自己独立开发的部分：源码取材排除脚手架原有文件，说明书不要描述脚手架自带功能，名称不要沿用原项目名")

    if (repo / ".git").exists():
        remotes = git(repo, "remote", "-v")
        urls = sorted({l.split()[1] for l in remotes.splitlines() if len(l.split()) > 1})
        for u in urls:
            public = re.search(r"github\.com|gitee\.com|gitlab\.com|gitcode", u, re.I)
            owner = re.search(r"(?:github\.com|gitee\.com|gitlab\.com|gitcode\.(?:com|net))[:/]([\w.-]+)/", u, re.I)
            mine = owner and _is_own(owner.group(1), tokens)
            if public and mine:
                F.add("low", "项目", ".git/config", "自有公开仓库", u, OWN_OSS_ADVICE)
            else:
                F.add("medium" if public else "low", "项目", ".git/config", "git 远程仓库", u,
                      "仓库所有者不在 self_aliases 中：确认是自己的仓库（补 self_aliases）还是他人项目/fork")
        if len([l for l in remotes.splitlines() if l.startswith("upstream")]):
            F.add("high", "项目", ".git/config", "存在 upstream 远程", "upstream",
                  "典型 fork 工作流：须核实上游项目的许可证与原作者权利，只申报自研部分")
        authors = [a for a in git(repo, "log", "--format=%an").splitlines() if a]
        if authors:
            uniq = sorted(set(authors))
            F.add("low", "项目", "git log", f"提交者 {len(uniq)} 人 / 提交 {len(authors)} 次",
                  "、".join(uniq[:8]) + ("…" if len(uniq) > 8 else ""),
                  "核对提交者是否均为著作权人或其员工/受托方；有外部贡献者需有书面授权")
        first = git(repo, "log", "--reverse", "--format=%s", "-n", "1").strip()
        if re.search(r"initial commit from|from template|clone|fork|import from|init from", first, re.I):
            F.add("medium", "项目", "git log", "首个提交疑似从模板/他人项目导入", first,
                  "确认初始代码来源与授权")


